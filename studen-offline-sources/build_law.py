import json, pathlib

DATA = pathlib.Path(__file__).resolve().parent.parent / "data"


def load(name):
    return json.loads((DATA / f"{name}.json").read_text(encoding="utf8"))


def save(name, value):
    (DATA / f"{name}.json").write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf8")


